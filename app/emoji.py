_CODE_RE = re.compile(r"\[([^\[\]]{1,6})\]")


def _unicode_present(text: str) -> list[str]:
    found: list[str] = []
    for ch in text:
        if ch in UNICODE and ch not in found:
            found.append(ch)
    return found


def gloss(text: str, limit: int = 6) -> list[str]:
    """返回「😅=尴尬、强颜欢笑」这种条目，只列这条消息里真出现的。"""
    if not text:
        return []
    out: list[str] = []
    for ch in _unicode_present(text):
        out.append(f"{ch}={UNICODE[ch]}")
        if len(out) >= limit:
            return out
    for code in _CODE_RE.findall(text):
        meaning = WECHAT.get(code)
        if meaning:
            item = f"[{code}]={meaning}"
            if item not in out:
                out.append(item)
        if len(out) >= limit:
            break
    return out


def note(text: str) -> str:
    """给模型看的一行注解；没有表情就返回空串。"""
    items = gloss(text)
    if not items:
        return ""
    return "（他这条带了表情：" + "；".join(items) + "，按这个感觉接）"
